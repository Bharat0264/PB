# ---- Bee Runner reports --------------------------------------------------------------------------------

RUNNER_PROBLEMS = {
    "customer_unreachable": ("Customer not answering", "high"),
    "wrong_address": ("Wrong address", "high"),
    "pickup_problem": ("Pickup problem", "high"),
    "safety": ("Safety issue", "urgent"),             # always urgent, which also emails the owner at once
}


def runner_problem_kinds():
    return [{"key": key, "label": label} for key, (label, _) in RUNNER_PROBLEMS.items()]


def create_runner_ticket(db, partner_id, order_id, kind, note=""):
    """A Bee Runner reports a problem on a delivery that is assigned to them. Returns the ticket id.

    The ticket belongs to no customer (its owner is "runner:<id>"), so no customer can ever see it; admins see it in
    the inbox with a Runner source badge. A repeat report of the same kind on the same order adds a message instead.
    """
    if kind not in RUNNER_PROBLEMS:
        raise SupportError("Choose what the problem is.")
    note = _text(note, "note", 1000, 0) if note else ""
    row = db.execute("SELECT orders.status FROM deliveries JOIN orders ON orders.id=deliveries.order_id "
                     "WHERE deliveries.order_id=? AND deliveries.partner=?", (order_id, partner_id)).fetchone() \
        if isinstance(order_id, str) else None
    if not row or row["status"] not in ("packed", "out_for_delivery"):
        raise NotFound("That delivery is not assigned to you.")
    label, priority = RUNNER_PROBLEMS[kind]
    owner = "runner:" + partner_id
    body = label + (". " + note if note else ".")
    existing = db.execute("SELECT id FROM support_tickets WHERE customer_email=? AND order_id=? AND subject=? AND status IN ('open','in_progress','pending') "
                          "ORDER BY id DESC LIMIT 1", (owner, order_id, "Runner: " + label)).fetchone()
    if existing:
        _add_message(db, existing["id"], "customer", owner, body)
        _touch(db, existing["id"])
        return existing["id"]
    return create_ticket(db, email=owner, category="runner", subject="Runner: " + label, message=body, order_id=order_id,
                         source="runner", priority=priority, actor=owner, order_checked=True)


