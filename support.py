def buzz_find_tickets(db, customer_email, *, query=None, status=None, limit=10):
    """Read only: this customer's own tickets, newest first, as the customer would see them."""
    email = _text(customer_email, "email", 254).lower()
    where, params = ["customer_email=?"], [email]
    if status in STATUSES:
        where.append("status=?"); params.append(status)
    elif status == "active":
        where.append("status IN ('open','in_progress','pending')")
    if query:
        like = "%" + str(query).strip().lower().replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_") + "%"
        where.append("(lower(subject) LIKE ? ESCAPE '\\' OR lower(ticket_number) LIKE ? ESCAPE '\\')")
        params += [like, like]
    rows = db.execute(f"SELECT * FROM support_tickets WHERE {' AND '.join(where)} ORDER BY updated DESC, id DESC LIMIT ?",
                      (*params, max(1, min(int(limit), 20)))).fetchall()
    return [_public_ticket(db, row) for row in rows]


