"""Generate theme-adapter.css from the dark-mode component rules in customer-theme.css.

customer-theme.css already restyles every major customer component (cards, nav, dock, inputs, account rows, cart,
checkout button ...) from variables instead of literal colours, for Moon Hive. The Theme Engine re-points those
variables at the active theme (theme-engine.css), so the same rules make the components follow any theme, in
light or dark. This script copies those rules under the "non-default theme" selector so they apply to every theme,
and swaps the few literal colours for tokens. Run it after editing the dark rules:

    python tools/build_theme_adapter.py          # rewrite theme-adapter.css
    python tools/build_theme_adapter.py --check  # exit 1 if theme-adapter.css is out of date
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "customer-theme.css"
TARGET = ROOT / "theme-adapter.css"
DARK = '[data-theme="dark"] .customer-theme'
THEMED = ':root[data-pb-theme]:not([data-pb-theme="printbee"]) .customer-theme'
LITERALS = {
    "#2a2112": "var(--pb-accent-ink)",
    "#ff9a8f": "var(--pb-danger)",
    "#f5c54255": "color-mix(in srgb, var(--pb-accent) 33%, transparent)",
}
HEADER = """/* GENERATED by tools/build_theme_adapter.py from the dark-mode rules in customer-theme.css. Do not edit by hand.
   Makes the customer components follow whichever theme is active (see THEMES.md). */
"""
EXTRA = f"""
/* Honey buttons and chips take the theme's accent. */
{THEMED} :is(.yellow, .pill.yellow, .brand-icon, .paper-seal) {{
  background: var(--pb-accent); color: var(--pb-accent-ink); box-shadow: var(--pb-shadow-raised);
}}
{THEMED} :is(.upload-orb, .cart-empty-orb, .cart-badge, .tile-icon) {{
  background: var(--pb-accent); color: var(--pb-accent-ink); box-shadow: var(--pb-shadow-raised);
}}
{THEMED} .segments input:checked + span {{ background: var(--pb-accent); color: var(--pb-accent-ink); }}
{THEMED} :is(.table-card, .upload-panel, .orders-card) {{ background: var(--pb-surface); }}
"""


def rules(css):
    """Split CSS into top-level rules, keeping comments out."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    depth, start, out = 0, 0, []
    for index, char in enumerate(css):
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                out.append(css[start:index + 1].strip())
                start = index + 1
    return out


def build():
    chosen = []
    for rule in rules(SOURCE.read_text(encoding="utf-8")):
        selectors = rule[:rule.index("{")]
        if DARK not in selectors or "logo" in selectors:      # the dark-lettered logo belongs to Moon Hive only
            continue
        chosen.append(rule.replace(DARK, THEMED))
    text = "\n".join(chosen)
    for literal, token in LITERALS.items():
        text = re.sub(re.escape(literal), token, text, flags=re.I)
    return HEADER + text + "\n" + EXTRA


if __name__ == "__main__":
    css = build()
    if "--check" in sys.argv:
        sys.exit(0 if TARGET.exists() and TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") == css else 1)
    TARGET.write_text(css, encoding="utf-8", newline="\n")
    print("wrote", TARGET.name, len(css), "bytes")
