"""Turn the PrintBee wordmark (the Lobster letters already shipped for the footer) into outline data for the Wildfire title.

    python tools/make_wildfire_title.py

Writes themes/wildfire-title.js: for every letter, its advance width and its shapes (an outer outline plus any holes) as flat
point lists in font units (y up). The hero extrudes those outlines into the 3D title with Three.js. Lobster is licensed under
the SIL Open Font License, which permits this. Needs fontTools (with brotli for woff2).
"""
import json
import math
from pathlib import Path

from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
TEXT = "PrintBee"
STEPS = 10


def flatten(ops):
    """Recording-pen operations -> list of closed contours (lists of (x, y))."""
    contours, current, last = [], [], None
    for op, args in ops:
        if op == "moveTo":
            current, last = [args[0]], args[0]
        elif op == "lineTo":
            current.append(args[0]); last = args[0]
        elif op == "qCurveTo":
            points = list(args)
            # TrueType implied on-curve points between consecutive off-curve points
            offs, end = points[:-1], points[-1]
            if end is None:
                continue
            segments, start = [], last
            for i, off in enumerate(offs):
                nxt = end if i == len(offs) - 1 else ((off[0] + offs[i + 1][0]) / 2, (off[1] + offs[i + 1][1]) / 2)
                segments.append((start, off, nxt)); start = nxt
            for p0, p1, p2 in segments:
                for s in range(1, STEPS + 1):
                    t = s / STEPS
                    current.append(((1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t * t * p2[0],
                                    (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t * t * p2[1]))
            last = end
        elif op == "curveTo":
            p0, (p1, p2, p3) = last, args
            for s in range(1, STEPS + 1):
                t = s / STEPS
                a, b, c, d = (1 - t) ** 3, 3 * (1 - t) ** 2 * t, 3 * (1 - t) * t * t, t ** 3
                current.append((a * p0[0] + b * p1[0] + c * p2[0] + d * p3[0], a * p0[1] + b * p1[1] + c * p2[1] + d * p3[1]))
            last = p3
        elif op in ("closePath", "endPath"):
            if len(current) > 2:
                contours.append(current)
            current = []
    return contours


def area(points):
    return sum(points[i][0] * points[(i + 1) % len(points)][1] - points[(i + 1) % len(points)][0] * points[i][1]
               for i in range(len(points))) / 2


def inside(point, polygon):
    x, y, hit = point[0], point[1], False
    for i in range(len(polygon)):
        (x1, y1), (x2, y2) = polygon[i], polygon[(i + 1) % len(polygon)]
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            hit = not hit
    return hit


def shapes_of(contours):
    """Group contours into shapes: contours turning the same way as the biggest one are outlines, the others are holes."""
    biggest = max(contours, key=lambda c: abs(area(c)))
    sign = math.copysign(1, area(biggest))
    outers = [c for c in contours if math.copysign(1, area(c)) == sign]
    holes = [c for c in contours if math.copysign(1, area(c)) != sign]
    shapes = [{"outer": o, "holes": []} for o in outers]
    for hole in holes:
        owner = min((s for s in shapes if inside(hole[0], s["outer"])), key=lambda s: abs(area(s["outer"])), default=shapes[0])
        owner["holes"].append(hole)
    return shapes


def main():
    font = TTFont(ROOT / "lobster-printbee-regular.woff2")
    glyphs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font["hmtx"]
    out = []
    for char in TEXT:
        name = cmap[ord(char)]
        pen = DecomposingRecordingPen(glyphs)
        glyphs[name].draw(pen)
        shapes = shapes_of(flatten(pen.value))
        round2 = lambda pts: [round(v, 1) for p in pts for v in p]  # noqa: E731
        out.append({"char": char, "advance": hmtx[name][0],
                    "shapes": [{"outer": round2(s["outer"]), "holes": [round2(h) for h in s["holes"]]} for s in shapes]})
    (ROOT / "themes" / "wildfire-title.js").write_text(
        "/* Generated by tools/make_wildfire_title.py from the Lobster wordmark letters (SIL OFL). Do not edit by hand. */\n"
        "export const TITLE = " + json.dumps({"text": TEXT, "unitsPerEm": font["head"].unitsPerEm, "glyphs": out}, separators=(",", ":")) + ";\n",
        encoding="utf-8", newline="\n")
    size = (ROOT / "themes" / "wildfire-title.js").stat().st_size
    print("wrote themes/wildfire-title.js", size, "bytes;", sum(len(g["shapes"]) for g in out), "shapes")


if __name__ == "__main__":
    main()
